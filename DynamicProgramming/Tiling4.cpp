/**
 * 백준온라인 14852 번 문제
 * : 2 * N 크기의 벽을 2 * 1, 1 * 2, 1 * 1 크기의 타일로 채우는 경우의 수를 구해보자.
 */

#include <stdio.h>

int d[1000001][2];

int dp(int x) {
  d[0][0] = 0;
  d[1][0] = 2;
  d[2][0] = 7;
  d[2][1] = 1;
  for(int i = 3; i <= x; i++) {
    d[i][1] = (d[i - 1][1] + d[i - 3][0]) % 100000007;
    d[i][0] = (3 * d[i - 2][0] + 2 * d[i - 1][0] + 2 * d[i][1]) % 100000007;
  }
  return d[x][0];
}

int main(void) {
  int x;
  scanf("%d", &x);
  printf("%d", dp(x));

  return 0;
}